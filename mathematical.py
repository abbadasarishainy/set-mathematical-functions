###Union
s1={10,20,30}
s2={40,50,60}
d=s1.union(s2)
print(d)
###intersection
s1={10,20,30}
s2={40,30,60}
s3=s1.intersection(s2)
print(s3)
##difference
s1={10,20,30}
s2={40,30,60}
s3=s1.difference(s2)
print(s3)

###difference_update()
s1={10,20,30}
s2={40,30,60}
s1.difference_update(s2)
print(s1)
###intersection_update()
s1={10,20,30,50}
s2={40,30,60,20}
s1.intersection_update(s2)
print(s1)
###symmetric difference update
s1={10,20,30,50}
s2={40,30,60,20}
s1.symmetric_difference_update(s2)
print(s1)
